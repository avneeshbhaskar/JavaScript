// Arithmetic Operator
let a = 10;
let b = 5;

console.log(a-b);
console.log(a*b);
console.log(a/b);
console.log(a%b);
console.log(a+b);
console.log(a**b);

// Unary Operators
console.log(a++);
console.log(++a);
console.log(a--);
console.log(--a);

// Assignment Operartor
b = a;
console.log(b);

// Comparison Operator
let age = 18;
console.log(age >= 18);
console.log(5 > 6);
console.log(a != b);
console.log(age <= 18);
console.log(4 == "4");
console.log(4 === "4");

// Comparison For Unicodes
console.log('a' > 'A')