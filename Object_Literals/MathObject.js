// Math object Methods // these all are Math objects
console.log(Math.random());  //generates random numbers from 0 to 1
console.log(Math.E); // E saved value
console.log(Math.PI); //3.14
console.log(Math.abs(-12.5)); //12.5
console.log(Math.pow(2,3));  //power
console.log(Math.floor(23.4999));  //round off
console.log(Math.floor(-5.5)); //-6 //round off to smallest one
console.log(Math.ceil(5.999)); //6 //round off to largest one
console.log(Math.ceil(-5.5)); //-5 //-5 is largest than -6

//Random Integers // in range of 1 to 10
let num = Math.random() * 10;   // multiply with 10
console.log(Math.floor(Math.random() * 10) + 1);  // num + 1
